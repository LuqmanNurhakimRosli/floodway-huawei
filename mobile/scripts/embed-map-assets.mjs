// Generates src/map/assets.generated.ts: Leaflet's JS and CSS, and a light copy of the stored road network, as strings
// the map WebView can use with no connection. Run after changing Leaflet or frontend/src/data/klRoutes.json:
//   node scripts/embed-map-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const leaflet = path.join(ROOT, 'node_modules', 'leaflet', 'dist');
const js = fs.readFileSync(path.join(leaflet, 'leaflet.js'), 'utf8');
const css = fs.readFileSync(path.join(leaflet, 'leaflet.css'), 'utf8');
const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', 'leaflet', 'package.json'), 'utf8')).version;

// roads: every stored route, deduplicated, every 3rd point, 5 decimals (about 1 m)
const db = JSON.parse(fs.readFileSync(path.resolve(ROOT, '../frontend/src/data/klRoutes.json'), 'utf8')).routes;
const seen = new Set();
const roads = [];
for (const raws of Object.values(db)) {
  for (const r of raws) {
    const line = r.line.filter((_, i) => i % 3 === 0 || i === r.line.length - 1).map(([a, b]) => [+a.toFixed(5), +b.toFixed(5)]);
    const key = line.filter((_, i) => i % 6 === 0).map((p) => p.join(',')).join('|');
    if (seen.has(key)) continue;
    seen.add(key);
    roads.push(line);
  }
}

const out = `// GENERATED by scripts/embed-map-assets.mjs. Do not edit by hand.
// Leaflet ${version} (BSD-2-Clause, (c) Volodymyr Agafonkin and contributors) and the stored Kuala Lumpur road routes
// (OpenStreetMap data, (c) OpenStreetMap contributors, ODbL).
export const LEAFLET_VERSION = ${JSON.stringify(version)};
export const LEAFLET_JS = ${JSON.stringify(js)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
export const OFFLINE_ROADS: [number, number][][] = ${JSON.stringify(roads)};
`;
fs.writeFileSync(path.join(ROOT, 'src', 'map', 'assets.generated.ts'), out);
console.log(`leaflet ${version}, ${roads.length} roads, ${(out.length / 1024).toFixed(0)} KB -> src/map/assets.generated.ts`);
